import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
import {CaptionState} from '../public/captions.mjs';
const c=new CaptionState();
assert.equal(c.userView('',{capturing:true}).placeholder,true);
assert.equal(c.userView('Ahoj, dneska',{capturing:true}).label,'Ty · živě');
assert.equal(c.userView('Ahoj, dneska',{finishing:true}).label,'Ty · dokončuji');
c.rememberUser('Ahoj, dneska mám volno.');
assert.equal(c.userView('',{capturing:true}).text,'Ahoj, dneska mám volno.','sent turn must stay visible while listening continues');
assert.equal(c.userView('',{}).text,'Ahoj, dneska mám volno.','stopping the microphone must not hide final transcript');
assert.equal(c.userView('Ještě něco.',{capturing:true}).text,'Ještě něco.');
assert.equal(c.addSegment('První věta.'),'První věta.');
assert.equal(c.addSegment('A druhá část.'),'První věta. A druhá část.');
c.beginReply();assert.equal(c.addSegment('Další odpověď.'),'Další odpověď.');
assert.equal(c.userView('',{}).text,'Ahoj, dneska mám volno.','new assistant reply must retain the human caption');
const app=await fs.readFile(new URL('../public/app.js',import.meta.url),'utf8');
const el={textContent:'',scrollTop:0,clientHeight:40,scrollHeight:80,classList:{remove(){}}};
const sandbox={captions:new CaptionState(),$:()=>el};
vm.createContext(sandbox);
const start=app.indexOf('function showSubtitle('),end=app.indexOf('\n}\n',start)+3;
vm.runInContext(app.slice(start,end),sandbox);
sandbox.showSubtitle('Ahoj.');sandbox.showSubtitle('Jak se máš?');
assert.equal(el.textContent,'Ahoj. Jak se máš?','TTS chunks must accumulate in the visible subtitle');
sandbox.captions.beginReply();sandbox.showSubtitle('<script>text</script>');
assert.equal(el.textContent,'<script>text</script>','caption rendering uses text, not HTML');
console.log('PASS partial transcript, final transcript after send/stop, independent speaker rows, complete multi-segment subtitles and safe text rendering.');
